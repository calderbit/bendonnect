// DepthLimit is the nesting limit baked into generated decoders and encoders.
const depthLimit = "100n"

type writer struct{ b strings.Builder }

func (w *writer) f(format string, a ...any) {
	if len(a) == 0 {
		w.b.WriteString(format)
	} else {
		fmt.Fprintf(&w.b, format, a...)
	}
	w.b.WriteByte('\n')
}
func (w *writer) blank()         { w.b.WriteByte('\n') }
func (w *writer) String() string { return w.b.String() }

// slot is one constructor field of a message: a plain field or a whole oneof.
type slot struct {
	Name   string
	Bind   string
	Type   string
	Def    string
	F      *field // plain field (nil for oneofs)
	O      *oneof
	MinNum int
}

func (m *message) slots() []*slot {
	if m.slotCache != nil {
		return m.slotCache
	}
	var out []*slot
	seen := map[*oneof]bool{}
	for _, f := range m.Decl {
		if f.Card == cOneof {
			if seen[f.Oneof] {
				continue
			}
			seen[f.Oneof] = true
			mn := f.Num
			for _, x := range f.Oneof.Members {
				if x.Num < mn {
					mn = x.Num
				}
			}
			out = append(out, &slot{Name: f.Oneof.Name, Bind: f.Oneof.Bind, Type: f.Oneof.Type, Def: f.Oneof.Type + ".None{}", O: f.Oneof, MinNum: mn})
			continue
		}
		out = append(out, &slot{Name: f.Name, Bind: f.Bind, Type: f.Type(), Def: f.Default(), F: f, MinNum: f.Num})
	}
	m.slotCache = out
	return out
}

func (m *message) slotsByNumber() []*slot {
	s := append([]*slot(nil), m.slots()...)
	sort.SliceStable(s, func(i, j int) bool { return s[i].MinNum < s[j].MinNum })
	return s
}

// pattern builds `M{a, _, c}` binding only the slots in use.
func (m *message) pattern(use func(*slot) bool) string {
	var parts []string
	for _, s := range m.slots() {
		if use(s) {
			parts = append(parts, s.Bind)
		} else {
			parts = append(parts, "_")
		}
	}
	return m.Name + "{" + strings.Join(parts, ", ") + "}"
}

// ctor builds `M{a, expr, c}` replacing one slot's expression.
func (m *message) ctor(repl map[*slot]string) string {
	var parts []string
	for _, s := range m.slots() {
		if e, ok := repl[s]; ok {
			parts = append(parts, e)
		} else {
			parts = append(parts, s.Bind)
		}
	}
	return m.Name + "{" + strings.Join(parts, ", ") + "}"
}

func (m *message) slotOf(f *field) *slot {
	for _, s := range m.slots() {
		if s.F == f || (s.O != nil && s.O == f.Oneof) {
			return s
		}
	}
	panic("slot not found")
}

func (f *field) isRepeatedLike() bool { return f.Card == cRepeated || f.Card == cMap }

func generate(gen *protogen.Plugin, file *protogen.File, runtimeOpt string) error {
	u, err := newUnit(gen, file)
	if err != nil {
		return err
	}
	if runtimeOpt == "" {
		return fmt.Errorf("plugin option runtime=<path to the Bendonnect root relative to the output directory, or a hub name like bendonnect-rpc@0.1.0.0> is required (e.g. runtime=../..)")
	}
	base := strings.TrimSuffix(file.Desc.Path(), ".proto")
	rt := runtimeOpt
	if isHubRef(rt) {
		rt = strings.TrimSuffix(rt, "/")
	} else {
		for d := path.Dir(base); d != "." && d != "" && d != "/"; d = path.Dir(d) {
			rt = path.Join(rt, "..")
		}
		rt = strings.TrimSuffix(rt, "/")
		if !strings.HasPrefix(rt, ".") && !strings.HasPrefix(rt, "/") {
			rt = "./" + rt
		}
	}
	w := &writer{}
	u.header(w, rt)
	u.typesSection(w)
	u.enumsSection(w)
	for _, m := range u.order {
		u.messageDefs(w, m)
	}
	out := gen.NewGeneratedFile(bendFile(base, "pb"), "")
	out.P(strings.TrimRight(w.String(), "\n"))
	if len(file.Services) > 0 {
		cw := &writer{}
		if err := u.connectFile(cw, rt, base); err != nil {
			return err
		}
		cout := gen.NewGeneratedFile(bendFile(base, "connect"), "")
		cout.P(strings.TrimRight(cw.String(), "\n"))
	}
	return nil
}

func (u *unit) header(w *writer, rt string) {
	w.f("# Code generated by protoc-gen-bend. DO NOT EDIT.")
	w.f("# source: %s", u.f.Desc.Path())
	if pkg := u.f.Desc.Package(); pkg != "" {
		w.f("# package: %s", pkg)
	}
	w.f("import Base")
	w.f("import bend-kit-bytes@0.3.2.0/bytes.bend as Bytes")
	w.f("import bend-kit-json@0.6.1.1/json.bend as Json")
	w.f("import bend-kit-protobuf@0.1.0.0/protobuf.bend as Pb")
	w.f("import %s/src/code.bend as Code", rt)
	w.f("import %s/src/error.bend as E", rt)
	w.f("import %s/src/protocol.bend as P", rt)
	w.f("import %s/src/pb.bend as Pbr", rt)
	w.f("import %s/src/pbjson.bend as Pj", rt)
	for _, d := range u.imports {
		w.f("import %s as %s", d.Path, d.Alias)
	}
	w.blank()
	w.f("# Maps a decode failure message to a Connect error (invalid_argument).")
	w.f("def lift_error(-T: Type, r: Result<&2, &1, String, T>) -> Result<&1, &1, E.Error, T>:")
	w.f("  match r:")
	w.f("    case Done{x}:")
	w.f("      Done{x}")
	w.f("    case Fail{msg}:")
	w.f("      Fail{E.new(Code.InvalidArgument{}, msg)}")
	w.blank()
	w.f("# A JSON array's elements (null is empty).")
	w.f("def json_items(v: Json.Val) -> Result<&2, &1, String, List<&1, Json.Val>>:")
	w.f("  match v:")
	w.f("    case Json.Null{}:")
	w.f("      Done{Nil{}}")
	w.f("    case Json.Arr{xs}:")
	w.f("      Done{xs}")
	w.f("    case Json.Flag{on}:")
	w.f("      Fail{\"expected a JSON array\"}")
	w.f("    case Json.Num{s}:")
	w.f("      Fail{\"expected a JSON array\"}")
	w.f("    case Json.Str{s}:")
	w.f("      Fail{\"expected a JSON array\"}")
	w.f("    case Json.Obj{kvs}:")
	w.f("      Fail{\"expected a JSON array\"}")
	w.blank()
	w.f("# A singular value as a list: [] for null, else [v].")
	w.f("def json_single(v: Json.Val) -> List<&1, Json.Val>:")
	w.f("  match v:")
	w.f("    case Json.Null{}:")
	w.f("      Nil{}")
	w.f("    case Json.Flag{on}:")
	w.f("      Con{Json.Flag{on}, Nil{}}")
	w.f("    case Json.Num{s}:")
	w.f("      Con{Json.Num{s}, Nil{}}")
	w.f("    case Json.Str{s}:")
	w.f("      Con{Json.Str{s}, Nil{}}")
	w.f("    case Json.Arr{xs}:")
	w.f("      Con{Json.Arr{xs}, Nil{}}")
	w.f("    case Json.Obj{kvs}:")
	w.f("      Con{Json.Obj{kvs}, Nil{}}")
	w.blank()
}

func (u *unit) typesSection(w *writer) {
	w.f("# ---------------------------------------------------------------- messages")
	w.blank()
	for _, m := range u.messages {
		var parts []string
		for _, s := range m.slots() {
			parts = append(parts, s.Name+": "+s.Type)
		}
		w.f("type %s is Data:", m.Name)
		w.f("  %s{%s}", m.Name, strings.Join(parts, ", "))
		w.blank()
		for _, o := range m.Oneofs {
			w.f("type %s is Data:", o.Type)
			w.f("  %s.None{}", o.Type)
			for _, f := range o.Members {
				w.f("  %s{value: %s}", f.Member, f.Elem)
			}
			w.blank()
		}
	}
}

func (u *unit) enumsSection(w *writer) {
	for _, e := range u.enums {
		w.f("# ---------------------------------------------------------------- enum %s", e.Name)
		w.blank()
		for _, v := range e.Values {
			w.f("def %s.%s() -> U32:", e.Name, v.Name)
			w.f("  %d", uint32(v.Num))
			w.blank()
		}
		w.f("def %s.name(+n: U32) -> String:", e.Name)
		w.f("  match n:")
		seen := map[int32]bool{}
		for _, v := range e.Values {
			if seen[v.Num] {
				continue
			}
			seen[v.Num] = true
			w.f("    case %d:", uint32(v.Num))
			w.f("      %q", v.Name)
		}
		w.f("    case _:")
		w.f("      \"\"")
		w.blank()
		w.f("def %s.from_name(+s: String) -> Maybe<&2, U32>:", e.Name)
		expr := "None{}"
		for i := len(e.Values) - 1; i >= 0; i-- {
			v := e.Values[i]
			expr = fmt.Sprintf("Bool.pick(Maybe<&2, U32>, String.eq(s, %q), Some{%d}, %s)", v.Name, uint32(v.Num), expr)
		}
		w.f("  %s", expr)
		w.blank()
		w.f("def %s.read_json(v: Json.Val) -> Result<&2, &1, String, U32>:", e.Name)
		w.f("  Pj.read.enum(~%s.from_name, v)", e.Name)
		w.blank()
	}
}

func (u *unit) messageDefs(w *writer, m *message) {
	w.f("# ---------------------------------------------------------------- message %s", m.Name)
	w.blank()
	// default
	var defs []string
	for _, s := range m.slots() {
		defs = append(defs, s.Def)
	}
	w.f("def %s.default() -> %s:", m.Name, m.Name)
	w.f("  %s{%s}", m.Name, strings.Join(defs, ", "))
	w.blank()
	if m.IsEntry {
		w.f("def %s.mk(+k: %s, +v: %s) -> %s:", m.Name, m.Decl[0].Elem, m.Decl[1].Elem, m.Name)
		w.f("  %s{k, v}", m.Name)
		w.blank()
	}
	u.protoDecode(w, m)
	u.protoEncode(w, m)
	u.jsonCodec(w, m)
	if !m.IsEntry {
		u.dispatch(w, m)
	}
}

func (u *unit) dispatch(w *writer, m *message) {
	n := m.Name
	w.f("def %s.encode(+codec: P.Codec, m: %s) -> Bytes.Bytes:", n, n)
	w.f("  match codec:")
	w.f("    case P.Json{}:")
	w.f("      %s.encode_json(m)", n)
	w.f("    case P.Proto{}:")
	w.f("      %s.encode_proto(m)", n)
	w.f("    case P.Custom{name}:")
	w.f("      Bytes.new(0)")
	w.blank()
	w.f("def %s.decode(+codec: P.Codec, b: Bytes.Bytes) -> Result<&1, &1, E.Error, %s>:", n, n)
	w.f("  match codec:")
	w.f("    case P.Json{}:")
	w.f("      lift_error(%s, %s.decode_json(b))", n, n)
	w.f("    case P.Proto{}:")
	w.f("      lift_error(%s, %s.decode_proto(b))", n, n)
	w.f("    case P.Custom{name}:")
	w.f("      Fail{E.new(Code.Unimplemented{}, \"codec not supported: \" ++ name)}")
	w.blank()
}

// bendFile names a generated module. Bend module names must be plain (letters, digits, _ and -),
// so "greet.proto" becomes greet_pb.bend and greet_connect.bend rather than greet.pb.bend.
func bendFile(base, kind string) string {
	dir, name := path.Split(base)
	var b strings.Builder
	for _, r := range name {
		if r == '-' || r == '_' || (r >= '0' && r <= '9') || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	return dir + b.String() + "_" + kind + ".bend"
}

// isHubRef reports whether the runtime option names a BendHub package (bendonnect-rpc@0.1.0.0 or
// 0x<hash>) rather than a local directory; hub imports are used verbatim.
func isHubRef(rt string) bool {
	first := strings.SplitN(rt, "/", 2)[0]
	return strings.Contains(first, "@") || (strings.HasPrefix(first, "0x") && len(first) > 2)
}
