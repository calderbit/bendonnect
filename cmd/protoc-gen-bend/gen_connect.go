package main

import (
	"fmt"
	"strings"
	"unicode"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/descriptorpb"
)

// snake converts an RPC name (GreetMany, HTTPGet) to snake_case (greet_many, http_get).
func snake(s string) string {
	rs := []rune(s)
	var b strings.Builder
	for i, r := range rs {
		if unicode.IsUpper(r) {
			prevLower := i > 0 && (unicode.IsLower(rs[i-1]) || unicode.IsDigit(rs[i-1]))
			acronymEnd := i > 0 && unicode.IsUpper(rs[i-1]) && i+1 < len(rs) && unicode.IsLower(rs[i+1])
			if prevLower || acronymEnd {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
		} else {
			b.WriteRune(r)
		}
	}
	return esc(b.String())
}

const (
	kUnary = iota
	kServerStream
	kClientStream
	kBidi
)

type method struct {
	Name, Snake string
	Proc        string
	Kind        int
	Req, Res    string // Bend type names (qualified)
	Get         bool
	Doc         string
}

func (u *unit) connectFile(w *writer, rt, base string) error {
	pbFile := bendFile(base, "pb")
	w.f("# Code generated by protoc-gen-bend. DO NOT EDIT.")
	w.f("# source: %s", u.f.Desc.Path())
	w.f("# Connect server and client stubs. The messages live in %s.", pbFile[strings.LastIndex(pbFile, "/")+1:])
	w.f("import Base")
	w.f("import %s/src/error.bend as E", rt)
	w.f("import %s/src/protocol.bend as P", rt)
	w.f("import %s/src/transport/server.bend as Srv", rt)
	w.f("import %s/src/transport/client.bend as Cli", rt)
	w.f("import %s/src/transport/rpc.bend as Rpc", rt)
	w.f("import ./%s as Msgs", pbFile[strings.LastIndex(pbFile, "/")+1:])
	for _, d := range u.imports {
		w.f("import %s as %s", d.Path, d.Alias)
	}
	w.blank()
	for _, svc := range u.f.Services {
		if err := u.service(w, svc); err != nil {
			return err
		}
	}
	return nil
}

// msgRef names a message type from the connect file: local ones live in Msgs.
func (u *unit) connectRef(m *protogen.Message) string {
	if m.Desc.ParentFile().Path() == u.f.Desc.Path() {
		return "Msgs." + relName(m.Desc)
	}
	return u.refName(m.Desc)
}

func (u *unit) service(w *writer, svc *protogen.Service) error {
	sname := relName(svc.Desc)
	if err := u.define(sname, "service "+string(svc.Desc.FullName())); err != nil {
		return err
	}
	var ms []*method
	seen := map[string]string{}
	for _, m := range svc.Methods {
		me := &method{Name: m.GoName, Snake: snake(string(m.Desc.Name())), Req: u.connectRef(m.Input), Res: u.connectRef(m.Output)}
		me.Proc = fmt.Sprintf("%s/%s", svc.Desc.FullName(), m.Desc.Name())
		if prev, ok := seen[me.Snake]; ok {
			return fmt.Errorf("service %s: methods %s and %s both map to the Bend name %q", svc.Desc.FullName(), prev, m.Desc.Name(), me.Snake)
		}
		seen[me.Snake] = string(m.Desc.Name())
		switch {
		case m.Desc.IsStreamingClient() && m.Desc.IsStreamingServer():
			me.Kind = kBidi
		case m.Desc.IsStreamingClient():
			me.Kind = kClientStream
		case m.Desc.IsStreamingServer():
			me.Kind = kServerStream
		default:
			me.Kind = kUnary
		}
		if opts, ok := m.Desc.Options().(*descriptorpb.MethodOptions); ok && opts != nil {
			me.Get = me.Kind == kUnary && opts.GetIdempotencyLevel() == descriptorpb.MethodOptions_NO_SIDE_EFFECTS
		}
		ms = append(ms, me)
	}
	w.f("# ---------------------------------------------------------------- service %s", svc.Desc.FullName())
	w.blank()
	for _, m := range ms {
		w.f("def %s.%s.procedure() -> String:", sname, m.Name)
		w.f("  %q", m.Proc)
		w.blank()
	}
	// owns
	var cond []string
	for _, m := range ms {
		cond = append(cond, fmt.Sprintf("String.eq(procedure, %s.%s.procedure())", sname, m.Name))
	}
	w.f("# True when procedure (\"pkg.Service/Method\") belongs to this service.")
	w.f("def %s.owns(+procedure: String) -> Bool:", sname)
	if len(cond) == 0 {
		w.f("  False{}")
	} else {
		w.f("  %s", strings.Join(cond, " || "))
	}
	w.blank()
	// server send helpers
	for _, m := range ms {
		if m.Kind == kServerStream {
			w.f("# Sends one %s on the %s stream.", m.Res, m.Name)
			w.f("def %s.%s.send(out: Rpc.Out, msg: %s) -> IO(Rpc.Out):", sname, m.Name, m.Res)
			w.f("  Rpc.send(~%s, ~%s.encode, out, msg)", m.Res, m.Res)
			w.blank()
		}
	}
	// handle
	var params []string
	for _, m := range ms {
		switch m.Kind {
		case kUnary:
			params = append(params, fmt.Sprintf("~%s: Rpc.Ctx -> %s -> IO(Result<&1, &1, E.Error, %s>)", m.Snake, m.Req, m.Res))
		case kServerStream:
			params = append(params, fmt.Sprintf("~%s: Rpc.Ctx -> %s -> Rpc.Out -> IO(Rpc.Out & Result<&1, &1, E.Error, Unit>)", m.Snake, m.Req))
		case kClientStream:
			params = append(params, fmt.Sprintf("~%s: Rpc.Ctx -> List<&2, %s> -> IO(Result<&1, &1, E.Error, %s>)", m.Snake, m.Req, m.Res))
		}
	}
	params = append(params, "call: Srv.Call")
	w.f("# Serves one call: routes by procedure to the matching handler (one template per method, in")
	w.f("# .proto order; bidirectional streaming methods answer Unimplemented). Unknown procedure: 404.")
	w.f("def %s.handle(%s) -> IO(Srv.Reply):", sname, strings.Join(params, ", "))
	expr := "Rpc.no_route(c)"
	_ = expr
	// build nested routes from the last method backwards
	miss := "Rpc.no_route"
	for i := len(ms) - 1; i >= 0; i-- {
		m := ms[i]
		var hit string
		switch m.Kind {
		case kUnary:
			hit = fmt.Sprintf("(c => Rpc.unary(~%s, ~%s, ~%s.decode, ~%s.encode, ~%s, c))", m.Req, m.Res, m.Req, m.Res, m.Snake)
		case kServerStream:
			hit = fmt.Sprintf("(c => Rpc.server_stream(~%s, ~%s.decode, ~%s, c))", m.Req, m.Req, m.Snake)
		case kClientStream:
			hit = fmt.Sprintf("(c => Rpc.client_stream(~%s, ~%s, ~%s.decode, ~%s.encode, ~%s, c))", m.Req, m.Res, m.Req, m.Res, m.Snake)
		case kBidi:
			hit = "Rpc.bidi_unimplemented"
		}
		missArg := miss
		if strings.HasPrefix(miss, "(") {
			missArg = miss
		}
		next := fmt.Sprintf("(c => Rpc.route(~%s, ~%s, %s.%s.procedure(), c))", hit, missArg, sname, m.Name)
		miss = next
	}
	if len(ms) == 0 {
		w.f("  Rpc.no_route(call)")
	} else {
		w.f("  %s(call)", miss)
	}
	w.blank()
	// client
	for _, m := range ms {
		hdr := "base_url: String, +codec: P.Codec, headers: Map<&2, List<&2, String>>"
		switch m.Kind {
		case kUnary:
			w.f("def %s.%s(%s, req: %s) -> IO(Result<&1, &1, E.Error, %s>):", sname, m.Snake, hdr, m.Req, m.Res)
			w.f("  Rpc.call.unary(~%s, ~%s, ~%s.decode, ~%s.encode, base_url, %s.%s.procedure(), codec, headers, req)", m.Req, m.Res, m.Res, m.Req, sname, m.Name)
			w.blank()
			if m.Get {
				w.f("# HTTP GET variant (the method is marked NO_SIDE_EFFECTS).")
				w.f("def %s.%s_get(%s, req: %s) -> IO(Result<&1, &1, E.Error, %s>):", sname, m.Snake, hdr, m.Req, m.Res)
				w.f("  do IO<Result<&1, &1, E.Error, %s>>:", m.Res)
				w.f("    r : Result<&1, &1, E.Error, Cli.Response> <- Cli.get(base_url, %s.%s.procedure(), codec, headers, %s.encode(codec, req))", sname, m.Name, m.Req)
				w.f("    return Rpc.one_res(~%s, ~%s.decode, codec, r)", m.Res, m.Res)
				w.blank()
			}
		case kServerStream:
			w.f("def %s.%s(%s, req: %s) -> IO(Result<&1, &1, E.Error, List<&2, %s>>):", sname, m.Snake, hdr, m.Req, m.Res)
			w.f("  Rpc.call.server_stream(~%s, ~%s, ~%s.decode, ~%s.encode, base_url, %s.%s.procedure(), codec, headers, req)", m.Req, m.Res, m.Res, m.Req, sname, m.Name)
			w.blank()
		case kClientStream:
			w.f("def %s.%s(%s, reqs: List<&2, %s>) -> IO(Result<&1, &1, E.Error, %s>):", sname, m.Snake, hdr, m.Req, m.Res)
			w.f("  Rpc.call.client_stream(~%s, ~%s, ~%s.decode, ~%s.encode, base_url, %s.%s.procedure(), codec, headers, reqs)", m.Req, m.Res, m.Res, m.Req, sname, m.Name)
			w.blank()
		case kBidi:
			w.f("# %s is bidirectional streaming: the HTTP/1.1 transport cannot carry it, so there is no client", m.Name)
			w.f("# function here and the server answers Unimplemented.")
			w.blank()
		}
	}
	return nil
}
